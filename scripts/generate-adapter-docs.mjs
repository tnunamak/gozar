// Generates docs/providers.md from the adapter registry (adapters/manifest.json `providers` and each
// definition). `--check` fails when the committed file differs. Nothing in the table is typed by hand.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const adapters = new URL('../adapters/', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('manifest.json', adapters), 'utf8'));
const cell = value => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
const flag = value => (value ? 'yes' : 'no');
const rows = [];
for (const provider of manifest.providers) {
  const { adapter } = JSON.parse(await readFile(new URL(provider.definition, adapters), 'utf8'));
  const c = adapter.capabilities;
  const ports = c.address.ports?.length ? c.address.ports.join(', ') : 'provider assigns';
  const proof = c.proof ? `${c.proof.vantage}: ${c.proof.checks.join(', ') || 'no checks'}` : 'none';
  rows.push(`| \`${adapter.id}\` | ${cell(adapter.label)} | ${cell(adapter.needs ?? '')} | ${adapter.supportedKinds.join(', ') || 'none yet'} | ${c.reach} | ${c.address.stability} | ${ports} | ${proof} | ${c.traffic.providerCanReadPayload === null ? 'unknown' : c.traffic.providerCanReadPayload ? 'provider can read' : 'endpoint only'} | ${flag(c.protocols.sse)} / ${flag(c.protocols.streamableHttp)} / ${flag(c.protocols.oauthDcr)} | ${cell(c.cost.summary)} |`);
}
const text = `<!-- Generated by scripts/generate-adapter-docs.mjs from adapters/manifest.json. Do not edit by hand. -->
# Route providers

Apps never name a provider. They state requirements and Gozar's catalog returns the providers that meet them.
This table lists what the registry ships. Each row is read from the provider's definition, so it is exactly
what \`catalogRoutes\` reports. The Id column is the value \`Query.providerId\` takes. Ports are the public
ports Gozar tries, in order. Proof is what Gozar checks before it publishes.

Gozar 0.2.0 supports Linux and macOS. On any other platform (for example Windows) every candidate answers
\`unsupported\`.

| Id | Name | Needs | Usage kinds | Reach | Address | Ports | Proof (vantage: checks) | Payload | SSE / streamable HTTP / OAuth DCR | Cost |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`;
const path = fileURLToPath(new URL('../docs/providers.md', import.meta.url));
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8').catch(() => '') !== text) { console.error('docs/providers.md is stale: run node scripts/generate-adapter-docs.mjs'); process.exit(1); }
} else await writeFile(path, text);
